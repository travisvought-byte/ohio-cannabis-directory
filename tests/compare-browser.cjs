const {chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{
 const server=await require('./server.cjs')(),browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
  await page.route('**/gc.zgo.at/**',r=>r.abort());await page.goto(server.base+'compare.html');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal scroll on a phone');
  assert.equal(await page.locator('#topic-license-limits .state').count(),4,'all four configured state columns render');
  assert(await page.locator('#topic-growing-space .state.missing').count()>=1,'unreviewed states are labeled');
  assert.match(await page.locator('.assessment .tag').first().textContent(),/analysis, not fact/);
  for(const href of await page.locator('.cites a').evaluateAll(as=>as.map(a=>a.getAttribute('href'))))assert.equal(await page.locator(href).count(),1,href+' resolves to a listed source');
  const key='oversupply-price-collapse',letter=page.locator('#letter-'+key);
  assert.match(await letter.inputValue(),/Keep the requests you agree with/);
  await page.locator('#form-'+key+' input[value="publish-data"]').check();
  await page.locator('#town-'+key).fill('PRIVATE_TOWN_123');await page.locator('#name-'+key).fill('Private Tester');
  let draft=await letter.inputValue();assert.match(draft,/PRIVATE_TOWN_123, Ohio/);assert.match(draft,/publish, each year/);assert.doesNotMatch(draft,/House Bill 4121/);assert.match(draft,/Private Tester$/);
  await letter.fill(draft+'\nManual edit.');await page.locator('#town-'+key).fill('Columbus');
  assert.match(await letter.inputValue(),/Manual edit\./,'manual edits survive later field changes');
  assert.match(await page.locator('#status-'+key).textContent(),/edits are kept/);
  await page.locator('#rebuild-'+key).click();assert.doesNotMatch(await letter.inputValue(),/Manual edit/);assert.match(await letter.inputValue(),/Columbus, Ohio/);
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>Promise.reject(new Error('denied'))},configurable:true}));
  await page.locator('#copy-'+key).click();assert.match(await page.locator('#status-'+key).textContent(),/copied/);
  assert(!requests.some(url=>url.includes('PRIVATE_TOWN_123')||url.includes('Private')),'letter details never leave the page');
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  await page.setViewportSize({width:1280,height:900});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  // Home-state proposals must change jurisdiction, preserve edits and keep exports private.
  await page.setViewportSize({width:390,height:844});
  await page.selectOption('#policy-home','MI');
  const proposal=page.locator('#policy-draft');
  assert.match(await proposal.inputValue(),/\[your town\], Michigan/);
  assert.match(await proposal.inputValue(),/For comparison, Ohio/);
  assert.match(await proposal.inputValue(),/MCL 333\.27959/);
  assert.match(await proposal.inputValue(),/https:\/\/codes\.ohio\.gov/);
  assert.equal(await page.locator('#policy-model option[value="MI"]').count(),0,'home state cannot be its own model');
  assert.match(await page.locator('#policy-lawmakers').innerText(),/Michigan senator/);
  assert.equal(await page.locator('#policy-lawmakers a[href="lawmakers.html"]').count(),0,'Michigan routes cannot use Ohio roster');
  await page.locator('#policy-goal').fill('PRIVATE_PROPOSAL_123: Allow smaller independent entrants.');
  await page.locator('#policy-town').fill('PRIVATE_TOWN_456');
  await page.locator('#policy-name').fill('PRIVATE_NAME_789');
  assert.match(await proposal.inputValue(),/PRIVATE_TOWN_456, Michigan/);
  assert.match(await proposal.inputValue(),/PRIVATE_PROPOSAL_123/);
  await proposal.fill((await proposal.inputValue())+'\nKeep my changes.');
  await page.selectOption('#policy-home','OH');
  assert.match(await proposal.inputValue(),/Keep my changes/);
  assert.match(await proposal.inputValue(),/PRIVATE_TOWN_456, Michigan/,'changing home cannot silently rewrite an edited letter');
  await page.locator('#policy-copy').click();
  assert.match(await page.locator('#policy-status').innerText(),/earlier state or topic/,'stale jurisdiction cannot be exported silently');
  await page.locator('#policy-rebuild').click();
  assert.match(await proposal.inputValue(),/PRIVATE_TOWN_456, Ohio/);
  assert.doesNotMatch(await proposal.inputValue(),/Keep my changes/);
  await page.selectOption('#policy-model','OR');
  assert.match(await proposal.inputValue(),/For comparison, Oregon/);
  await page.selectOption('#policy-topic','growing-space');
  assert.equal(await page.locator('#policy-model option[value="OR"]').count(),0,'unreviewed model topics cannot enter letters');
  assert.match(await proposal.inputValue(),/For comparison, Michigan/);
  await page.locator('#policy-copy').click();
  assert.match(await page.locator('#policy-status').innerText(),/copied/,'portal clipboard fallback works');
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#policy-download').click()]);
  const fs=require('node:fs');
  assert.equal(fs.readFileSync(await download.path(),'utf8'),await proposal.inputValue(),'download includes the exact edited draft');
  await download.delete();
  await page.evaluate(()=>window.print=()=>{});
  await page.locator('#policy-print').click();await page.emulateMedia({media:'print'});
  assert.equal(await page.locator('#policy-print-text').innerText(),await proposal.inputValue());
  assert.equal(await page.locator('#lessons').isVisible(),false,'proposal prints without unrelated Ohio analysis');
  await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));await page.emulateMedia({media:'screen'});
  assert.equal(await page.locator('#lessons').isVisible(),true);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'portal fits phone width');
  assert(!requests.some(url=>/PRIVATE_PROPOSAL|PRIVATE_TOWN|PRIVATE_NAME/.test(url)),'portal personal text never leaves the page');
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  await page.reload();assert.doesNotMatch(await proposal.inputValue(),/PRIVATE_/,'no personal text is persisted');
  assert.deepEqual(errors,[]);
  const plain=await browser.newContext({javaScriptEnabled:false}),fallback=await plain.newPage();await fallback.goto(server.base+'compare.html');
  assert.match(await fallback.locator('#letter-'+key).inputValue(),/Keep the requests you agree with/);assert.match(await fallback.locator('#policy-portal').innerText(),/Michigan senator lookup/);await plain.close();
  console.log('PASS: state comparison and Ohio/Michigan proposals, reviewed model coverage, jurisdiction-safe edits/exports, download, print, mobile width, citations, clipboard fallback, privacy and no-JS routes.');
 }finally{await browser.close();await server.close();}
})().catch(e=>{console.error(e);process.exit(1)});
